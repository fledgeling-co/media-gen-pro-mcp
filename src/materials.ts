/**
 * Provenance for files written into a motion-craft project.
 *
 * motion-craft, the skill that builds films from code, keeps everything a film
 * uses in `<project>/materials/` and lists each file with its source in
 * `materials.md`: every claim, logo and screen in the film has to trace to that
 * list, and anything synthetic has to be labelled as such so it lands on the
 * replacement list rather than passing for real material. A generated clip
 * written there without an entry is exactly the untraceable asset that rule
 * exists to catch, so when `outputDir` is a motion-craft project's materials
 * folder, each generated file gets its entry here.
 *
 * Recognised by layout, not configured: the folder is named `materials` and its
 * parent holds a file only a motion-craft (or HyperFrames) project writes.
 * Append-only, so nothing the project already recorded is touched.
 */

import { existsSync } from 'node:fs';
import { appendFile, readFile } from 'node:fs/promises';
import { basename, dirname, join, relative, resolve } from 'node:path';

const PROJECT_MARKERS = ['BRIEF.md', 'SPEC.md', 'STORYLINES.md', 'timeline.json', 'hyperframes.json'] as const;
const SECTION = '## Generated by media-gen-pro';

export interface MaterialEntry {
  /** Absolute path of the file that was written. */
  readonly path: string;
  /** "image", "SVG" or "video". */
  readonly kind: string;
  /** Model label and route, e.g. "Seedance 2.0 via the gateway". */
  readonly model: string;
  readonly prompt: string;
  /** Extra facts worth keeping beside the entry: duration, aspect, a source frame. */
  readonly details?: readonly string[];
}

/** The project root when `outputDir` is a motion-craft project's materials folder, else undefined. */
export function motionCraftProject(outputDir: string): string | undefined {
  const dir = resolve(outputDir);
  if (basename(dir) !== 'materials') return undefined;
  const root = dirname(dir);
  return PROJECT_MARKERS.some((m) => existsSync(join(root, m))) ? root : undefined;
}

/**
 * Where the project's list lives. motion-craft lays it out beside the folder
 * (`<project>/materials.md`); a list already inside the folder is respected.
 */
export function materialsList(root: string): string {
  const inside = join(root, 'materials', 'materials.md');
  return existsSync(inside) ? inside : join(root, 'materials.md');
}

const oneLine = (s: string, max: number): string => {
  const flat = s.replace(/\s+/g, ' ').trim().replace(/"/g, "'");
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat;
};

export function formatEntry(root: string, e: MaterialEntry, date: string): string {
  const facts = [e.model, ...(e.details ?? []), date].join(', ');
  return (
    `- \`${relative(root, e.path)}\`: generated ${e.kind}, ${facts}. ` +
    'Synthetic, not real product material: put it on the replacement list wherever the film presents it as real. ' +
    `Prompt: "${oneLine(e.prompt, 400)}"`
  );
}

/**
 * Append entries for files written into a motion-craft project. Returns the
 * list's path when something was recorded, so the caller can say so.
 */
export async function recordMaterials(
  outputDir: string,
  entries: readonly MaterialEntry[],
  date: string = new Date().toISOString().slice(0, 10),
): Promise<string | undefined> {
  const root = motionCraftProject(outputDir);
  if (!root || entries.length === 0) return undefined;
  const list = materialsList(root);
  const existing = existsSync(list) ? await readFile(list, 'utf8') : '';
  // Entries go at the end of the file, so they sit under this section only when it
  // is the last heading; otherwise the heading is written again rather than
  // filing generated clips under someone else's section.
  const lastHeading = existing.split('\n').filter((l) => l.startsWith('## ')).pop();
  const gap = existing === '' || existing.endsWith('\n\n') ? '' : existing.endsWith('\n') ? '\n' : '\n\n';
  const header = lastHeading === SECTION ? (existing.endsWith('\n') ? '' : '\n') : `${gap}${SECTION}\n\n`;
  const body = entries.map((e) => formatEntry(root, e, date)).join('\n');
  await appendFile(list, `${header}${body}\n`, 'utf8');
  return list;
}
