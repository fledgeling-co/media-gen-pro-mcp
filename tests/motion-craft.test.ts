import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { motionCraftNote, motionGraphicTrait } from '../src/advice.js';
import { materialsList, motionCraftProject, recordMaterials } from '../src/materials.js';

describe('spotting a motion graphic in a video prompt', () => {
  it.each([
    ['Kinetic typography: the words "Ship faster" slam in one by one', 'words on screen'],
    ['A lower third with the speaker name slides in', 'words on screen'],
    ['Logo reveal for Acme, the mark assembles from particles', 'a logo animation'],
    ['An animated bar chart of quarterly revenue that grows from zero', 'a chart or numbers that animate'],
    ['Numbers count up to 1,200 customers', 'a chart or numbers that animate'],
    ['Product demo of our app interface: a cursor clicks Export', 'a product or interface demo'],
    ['A screen recording of the analytics dashboard scrolling', 'a product or interface demo'],
    ['A 30 second explainer about how the API works', 'an explainer or motion graphic'],
  ])('%s', (prompt, trait) => {
    expect(motionGraphicTrait(prompt)).toBe(trait);
    expect(motionCraftNote(prompt)).toContain('motion-craft:motion-craft');
  });

  it.each([
    'Steam rises from a mug on the kitchen counter, slow push-in',
    'A child slides down a red slide in a sunlit park',
    'Rain on the car dashboard as the wipers sweep, camera static',
    'A sailor unrolls a nautical chart on a wooden table, candle flickers',
    'A real estate walkthrough of a bright apartment, gimbal glides forward',
    'She turns to face the window as the light shifts',
  ])('leaves footage alone: %s', (prompt) => {
    expect(motionGraphicTrait(prompt)).toBeUndefined();
    expect(motionCraftNote(prompt)).toBeUndefined();
  });
});

describe('recording generated files in a motion-craft project', () => {
  const project = async (markers: string[], existing?: { at: 'root' | 'inside'; text: string }) => {
    const root = await mkdtemp(join(tmpdir(), 'mgp-motion-'));
    await mkdir(join(root, 'materials'));
    for (const m of markers) await writeFile(join(root, m), '');
    if (existing) {
      await writeFile(existing.at === 'root' ? join(root, 'materials.md') : join(root, 'materials', 'materials.md'), existing.text);
    }
    return root;
  };

  it('recognises the materials folder of a project with a brief or spec', async () => {
    const root = await project(['SPEC.md']);
    expect(motionCraftProject(join(root, 'materials'))).toBe(root);
    expect(motionCraftProject(root)).toBeUndefined();
  });

  it('ignores a folder called materials that belongs to nothing', async () => {
    const root = await project([]);
    expect(motionCraftProject(join(root, 'materials'))).toBeUndefined();
    expect(await recordMaterials(join(root, 'materials'), [{ path: join(root, 'materials', 'x.png'), kind: 'image', model: 'M', prompt: 'p' }])).toBeUndefined();
  });

  it('writes the list beside the folder, labelled synthetic, with model, details and prompt', async () => {
    const root = await project(['BRIEF.md']);
    const list = await recordMaterials(
      join(root, 'materials'),
      [{ path: join(root, 'materials', 'harbour-1a2b3c.mp4'), kind: 'video', model: 'Seedance 2.0', prompt: 'Fog lifts off\nthe harbour, slow push-in', details: ['5 s', '16:9'] }],
      '2026-11-17',
    );
    expect(list).toBe(join(root, 'materials.md'));
    const text = await readFile(join(root, 'materials.md'), 'utf8');
    expect(text).toBe(
      '## Generated by media-gen-pro\n\n' +
        '- `materials/harbour-1a2b3c.mp4`: generated video, Seedance 2.0, 5 s, 16:9, 2026-11-17. ' +
        'Synthetic, not real product material: put it on the replacement list wherever the film presents it as real. Prompt: "Fog lifts off the harbour, slow push-in"\n',
    );
  });

  it('appends under its own heading without touching what the project recorded', async () => {
    const root = await project(['hyperframes.json'], { at: 'inside', text: '# Materials\n\n- logo.svg: from the brand site\n' });
    expect(materialsList(root)).toBe(join(root, 'materials', 'materials.md'));
    const entry = { path: join(root, 'materials', 'a.png'), kind: 'image', model: 'GPT Image', prompt: 'a' };
    await recordMaterials(join(root, 'materials'), [entry], '2026-11-17');
    await recordMaterials(join(root, 'materials'), [{ ...entry, path: join(root, 'materials', 'b.png') }], '2026-11-17');
    const text = await readFile(join(root, 'materials', 'materials.md'), 'utf8');
    expect(text.startsWith('# Materials\n\n- logo.svg: from the brand site\n\n## Generated by media-gen-pro\n\n- `materials/a.png`')).toBe(true);
    expect(text.match(/## Generated by media-gen-pro/g)).toHaveLength(1);
    expect(text).toContain('\n- `materials/b.png`');
  });

  it('starts its heading again when the project added a section after it', async () => {
    const root = await project(['SPEC.md'], { at: 'root', text: '## Generated by media-gen-pro\n\n- `materials/a.png`: x\n\n## Fonts\n\n- Inter\n' });
    await recordMaterials(join(root, 'materials'), [{ path: join(root, 'materials', 'c.png'), kind: 'image', model: 'M', prompt: 'c' }], '2026-11-17');
    const text = await readFile(join(root, 'materials.md'), 'utf8');
    expect(text.endsWith('## Fonts\n\n- Inter\n\n## Generated by media-gen-pro\n\n- `materials/c.png`: generated image, M, 2026-11-17. Synthetic, not real product material: put it on the replacement list wherever the film presents it as real. Prompt: "c"\n')).toBe(true);
  });
});
